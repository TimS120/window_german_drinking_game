"""Generate native app parity cases from a selected PyTorch checkpoint."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import torch
from export_onnx import DeploymentPolicy, load_checkpoint
from window_rl.deployment_fixtures import encode_fixture_history


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    torch.set_num_threads(1)
    model, payload = load_checkpoint(args.checkpoint)
    deployment = DeploymentPolicy(model, payload['training'].get('reward_scale', 1.)).eval()
    length = payload['training']['history_length']
    fixtures = []
    for name in ('recurrent_contract', 'recurrent_contract_v5'):
        fixtures += json.loads(Path(__file__).with_name(f'{name}.json').read_text())
    cases = []
    for fixture in fixtures:
        history = encode_fixture_history(fixture, length, model.history_encoder.input_size)
        legal = fixture['legalActions']
        with torch.no_grad():
            logits, value = deployment(torch.from_numpy(history))
            probabilities = logits[0, legal].softmax(0)
        order = sorted(range(len(legal)), key=lambda i: (-float(logits[0, legal[i]]), i))
        best = order[0]
        cases.append({'name': fixture['name'], 'state': fixture['state'],
                      'action': legal[best], 'value': float(value[0, 0]),
                      'confidence': float(probabilities[best]),
                      'secondAction': legal[order[1]] if len(order) > 1 else None,
                      'secondConfidence': float(probabilities[order[1]]) if len(order) > 1 else None})
    with args.checkpoint.open('rb') as source:
        digest = hashlib.file_digest(source, 'sha256').hexdigest()
    data = {'checkpointSha256': digest, 'cases': cases}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('// Generated by ml/fixtures/generate_deployment_probe.py. Test data only.\n'
                           "const String deploymentProbeJson =\n    r'''" + json.dumps(data, separators=(',', ':')) + "''';\n")
    print(f'Generated {len(cases)} native parity cases: {args.output}')


if __name__ == '__main__':
    main()
